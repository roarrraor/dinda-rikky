#!/usr/bin/env node
/**
 * Hasilkan daftar frame & stiker photobooth dari isi folder — supaya Roar
 * cukup UPLOAD file baru, tanpa ubah hardcode.
 *
 * Cara pakai (buat Roar):
 *   Frame   -> taruh gambar di public/assets/photobooth/frames/
 *   Stiker  -> taruh gambar di public/assets/stickers/
 *   lalu deploy ulang (push ke GitHub). File baru langsung muncul di picker.
 *
 * Konvensi nama file frame (opsional, pisahkan dengan --):
 *   <nama>[--klasik|--taman|--modern][--overlay][--fade-RRGGBB].webp
 *   contoh: daun-teh.webp            -> "Daun Teh", Taman, background
 *           daun-teh--klasik.webp    -> "Daun Teh", Klasik, background
 *           renda--overlay--strip.svg -> "Renda", Taman, overlay, strip saja
 *           malam--fade-232323.webp  -> fade footer warna #232323
 *   Tanpa sufiks: konsep Taman, layer background (semua layout),
 *   fade footer #F3EADB (krem).
 *
 * File yang sudah terdaftar di hardcode (IMAGE_FRAMES / STICKERS) dilewati
 * supaya tidak muncul dobel. Dijalankan otomatis sebelum build
 * (lihat "prebuild" di package.json) dan hasilnya ditulis ke
 * lib/wedding/photobooth-assets.generated.ts (file ini JANGAN diedit manual).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FRAMES_DIR = path.join(ROOT, "public", "assets", "photobooth", "frames");
const STICKERS_DIR = path.join(ROOT, "public", "assets", "stickers");
const OUT = path.join(ROOT, "lib", "wedding", "photobooth-assets.generated.ts");

const FRAME_EXTS = new Set([".webp", ".png", ".jpg", ".jpeg", ".svg"]);
const STICKER_EXTS = new Set([".gif", ".png", ".webp"]);
// File yang sengaja tidak dimunculkan (PNG Renda Teh yang ditolak Roar).
const SKIP_FRAMES = new Set(["renda-teh-strip.png"]);

const ALL_LAYOUTS = ["duo", "trio", "classic", "portrait"];
const CONCEPTS = ["klasik", "taman", "modern"];

function listFiles(dir, exts) {
  try {
    return fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isFile() && exts.has(path.extname(d.name).toLowerCase()))
      .map((d) => d.name)
      .sort();
  } catch {
    return [];
  }
}

/** Ambil semua src "..." dari sebuah file TS (buat lewati yang sudah hardcode). */
function hardcodedSrcs(file, prefix) {
  try {
    const text = fs.readFileSync(path.join(ROOT, file), "utf8");
    const out = new Set();
    for (const m of text.matchAll(/src:\s*"([^"]+)"/g)) {
      if (m[1].startsWith(prefix)) out.add(m[1]);
    }
    return out;
  } catch {
    return new Set();
  }
}

function humanize(slug) {
  return slug
    .split("-")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

function frameFromFile(file) {
  const ext = path.extname(file);
  const base = path.basename(file, ext);
  const parts = base.split("--");
  const slug = parts[0];
  const mods = parts.slice(1).map((m) => m.toLowerCase());
  let concept = "Taman";
  for (const c of CONCEPTS) {
    if (mods.includes(c)) {
      concept = c.charAt(0).toUpperCase() + c.slice(1);
      break;
    }
  }
  const layer = mods.includes("overlay") ? "overlay" : "background";
  let footerFade = "#F3EADB";
  const fade = mods.find((m) => m.startsWith("fade-"));
  if (fade) {
    const hex = fade.slice(5).replace(/[^0-9a-f]/gi, "").slice(0, 6);
    if (hex.length === 6) footerFade = `#${hex.toUpperCase()}`;
  }
  let layouts = ALL_LAYOUTS;
  if (layer === "overlay") {
    const picked = ALL_LAYOUTS.filter((l) => mods.includes(l));
    layouts = picked.length > 0 ? picked : ["trio"];
  }
  return {
    id: slug,
    name: humanize(slug),
    concept,
    src: `/assets/photobooth/frames/${file}`,
    layouts,
    footer: "drawn",
    layer,
    footerFade,
  };
}

function main() {
  const usedFrameSrcs = hardcodedSrcs("lib/wedding/photobooth.ts", "/assets/photobooth/frames/");
  const usedStickerSrcs = hardcodedSrcs("lib/wedding/stickers.ts", "/assets/stickers/");

  const frames = listFiles(FRAMES_DIR, FRAME_EXTS)
    .filter((f) => !SKIP_FRAMES.has(f))
    .filter((f) => !usedFrameSrcs.has(`/assets/photobooth/frames/${f}`))
    .map(frameFromFile);

  const stickers = listFiles(STICKERS_DIR, STICKER_EXTS)
    .filter((f) => !usedStickerSrcs.has(`/assets/stickers/${f}`))
    .map((f) => {
      const slug = path.basename(f, path.extname(f));
      return { key: slug, label: humanize(slug), src: `/assets/stickers/${f}` };
    });

  const header = `// Generated by scripts/gen-photobooth-assets.mjs — JANGAN EDIT MANUAL.
// Tambah frame/stiker baru: upload file ke foldernya, lalu deploy ulang.
// Lihat scripts/gen-photobooth-assets.mjs buat konvensi nama file.
import type { ImageFrame } from "./photobooth";
import type { StickerOption } from "./stickers";

export const DISCOVERED_FRAMES: ImageFrame[] = ${JSON.stringify(frames, null, 2)};

export const DISCOVERED_STICKERS: StickerOption[] = ${JSON.stringify(stickers, null, 2)};
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header);
  console.log(`photobooth assets: ${frames.length} frame baru, ${stickers.length} stiker baru -> ${path.relative(ROOT, OUT)}`);
}

main();
